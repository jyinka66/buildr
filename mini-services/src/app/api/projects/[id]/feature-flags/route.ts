// GET    /api/projects/[id]/feature-flags — list all feature flags
// POST   /api/projects/[id]/feature-flags — create/update a feature flag
// PATCH  /api/projects/[id]/feature-flags — toggle a flag on/off
// DELETE /api/projects/[id]/feature-flags?key=<key> — remove a flag
//
// Feature flags are stored in the project's db_config as a `featureFlags`
// field. Each flag has: key, enabled, description, rolloutPercentage.
// The generated code can read these flags via a generated feature-flag lib.
import { NextRequest, NextResponse } from 'next/server'
import { db } from '@/lib/db'
import { requireSessionUser } from '@/lib/session'
import { audit } from '@/lib/snapshot'

interface FeatureFlag {
  key: string
  enabled: boolean
  description: string
  rolloutPercentage: number // 0-100
}

async function getFlags(projectId: string): Promise<FeatureFlag[]> {
  const { data: project } = await db.from('projects').select('db_config').eq('id', projectId).maybeSingle()
  if (!project?.db_config) return []
  let config: Record<string, unknown>
  try {
    config = typeof project.db_config === 'string' ? JSON.parse(project.db_config) : project.db_config as Record<string, unknown>
  } catch { return [] }
  const flags = config.featureFlags
  return Array.isArray(flags) ? flags : []
}

async function setFlags(projectId: string, flags: FeatureFlag[]): Promise<void> {
  const { data: project } = await db.from('projects').select('db_config').eq('id', projectId).maybeSingle()
  let config: Record<string, unknown> = {}
  try { config = typeof project?.db_config === 'string' ? JSON.parse(project.db_config || '{}') : (project?.db_config as Record<string, unknown>) || {} } catch {}
  config.featureFlags = flags
  await db.from('projects').update({ db_config: JSON.stringify(config) }).eq('id', projectId)
}

async function assertOwnership(id: string) {
  const user = await requireSessionUser()
  const { data: project } = await db.from('projects').select('owner_id').eq('id', id).maybeSingle()
  if (!project) return { user, status: 404 } as const
  if (project.owner_id !== user.id) return { user, status: 403 } as const
  return { user, status: 200 } as const
}

export async function GET(
  _req: NextRequest,
  { params }: { params: Promise<{ id: string }> },
) {
  const { id } = await params
  let owner
  try { owner = await assertOwnership(id) } catch (err) {
    if ((err as { status?: number }).status === 401) return NextResponse.json({ error: 'unauthorized' }, { status: 401 })
    throw err
  }
  if (owner.status === 404) return NextResponse.json({ error: 'not_found' }, { status: 404 })
  if (owner.status === 403) return NextResponse.json({ error: 'forbidden' }, { status: 403 })
  const flags = await getFlags(id)
  return NextResponse.json({ flags })
}

interface CreateBody {
  key: string
  description: string
  enabled?: boolean
  rolloutPercentage?: number
}

export async function POST(
  req: NextRequest,
  { params }: { params: Promise<{ id: string }> },
) {
  const { id } = await params
  let user
  try { const o = await assertOwnership(id); user = o.user } catch (err) {
    if ((err as { status?: number }).status === 401) return NextResponse.json({ error: 'unauthorized' }, { status: 401 })
    throw err
  }
  const body = (await req.json()) as CreateBody
  const key = body.key?.trim().toLowerCase().replace(/[^a-z0-9_-]/g, '_')
  if (!key || !body.description) return NextResponse.json({ error: 'key and description are required.' }, { status: 400 })

  const flags = await getFlags(id)
  const idx = flags.findIndex((f) => f.key === key)
  const flag: FeatureFlag = {
    key,
    description: body.description,
    enabled: body.enabled ?? false,
    rolloutPercentage: body.rolloutPercentage ?? 100,
  }
  if (idx >= 0) flags[idx] = flag
  else flags.push(flag)

  await setFlags(id, flags)
  await audit('feature_flag.create', { key, enabled: flag.enabled }, user.id, id)

  // Also generate the feature-flag lib if it doesn't exist yet.
  const { data: existingLib } = await db.from('project_files').select('id').eq('project_id', id).eq('path', 'src/lib/feature-flags.ts').maybeSingle()
  if (!existingLib) {
    await db.from('project_files').insert({
      project_id: id,
      path: 'src/lib/feature-flags.ts',
      language: 'ts',
      content: `// Feature flags — generated by Buildr.
// Toggle features on/off without redeploying.
// Flags are managed in the Buildr builder and stored in the project config.

interface FeatureFlag {
  key: string;
  enabled: boolean;
  rolloutPercentage: number;
}

const flags: Record<string, FeatureFlag> = ${JSON.stringify(flags.reduce((acc, f) => { acc[f.key] = f; return acc }, {} as Record<string, FeatureFlag>), null, 2)};

/**
 * Check if a feature flag is enabled.
 * @param key - The flag key (e.g. "new-dashboard")
 * @param userId - Optional user ID for rollout percentage evaluation
 */
export function isFeatureEnabled(key: string, userId?: string): boolean {
  const flag = flags[key];
  if (!flag) return false;
  if (!flag.enabled) return false;
  if (flag.rolloutPercentage >= 100) return true;
  if (flag.rolloutPercentage <= 0) return false;
  // Deterministic hash-based rollout for consistent user experience.
  if (userId) {
    const hash = userId.split('').reduce((a, b) => ((a << 5) - a + b.charCodeAt(0)) | 0, 0);
    return (Math.abs(hash) % 100) < flag.rolloutPercentage;
  }
  return Math.random() * 100 < flag.rolloutPercentage;
}

/**
 * Get all feature flags.
 */
export function getAllFlags(): FeatureFlag[] {
  return Object.values(flags);
}
`,
      generated: true,
    })
  }

  return NextResponse.json({ ok: true, flag })
}

export async function PATCH(
  req: NextRequest,
  { params }: { params: Promise<{ id: string }> },
) {
  const { id } = await params
  let user
  try { const o = await assertOwnership(id); user = o.user } catch (err) {
    if ((err as { status?: number }).status === 401) return NextResponse.json({ error: 'unauthorized' }, { status: 401 })
    throw err
  }
  const body = await req.json()
  const key = body.key as string
  const enabled = body.enabled as boolean
  if (!key) return NextResponse.json({ error: 'key required' }, { status: 400 })

  const flags = await getFlags(id)
  const flag = flags.find((f) => f.key === key)
  if (!flag) return NextResponse.json({ error: 'flag not found' }, { status: 404 })
  flag.enabled = enabled
  await setFlags(id, flags)
  await audit('feature_flag.toggle', { key, enabled }, user.id, id)

  return NextResponse.json({ ok: true, flag })
}

export async function DELETE(
  req: NextRequest,
  { params }: { params: Promise<{ id: string }> },
) {
  const { id } = await params
  try { const o = await assertOwnership(id); if (o.status !== 200) return NextResponse.json({ error: 'forbidden' }, { status: o.status }) } catch (err) {
    if ((err as { status?: number }).status === 401) return NextResponse.json({ error: 'unauthorized' }, { status: 401 })
    throw err
  }
  const url = new URL(req.url)
  const key = url.searchParams.get('key')
  if (!key) return NextResponse.json({ error: 'key required' }, { status: 400 })

  const flags = await getFlags(id)
  const filtered = flags.filter((f) => f.key !== key)
  await setFlags(id, filtered)
  return NextResponse.json({ ok: true })
}
