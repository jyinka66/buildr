// GET /api/projects/[id]/docs — generates an OpenAPI 3.1 spec from the
// project's generated route.ts files. Scans each route file for exported
// HTTP method handlers (GET, POST, PUT, DELETE, PATCH) and builds a paths
// object. Optionally uses the LLM to infer request/response schemas from
// the handler code. Returns the spec as JSON.
import { NextRequest, NextResponse } from 'next/server'
import { db } from '@/lib/db'
import { requireSessionUser } from '@/lib/session'

// Extract HTTP method exports from a route file's source.
const METHODS = ['GET', 'POST', 'PUT', 'DELETE', 'PATCH'] as const

function extractRouteInfo(source: string): {
  methods: string[]
  summary: string
} {
  const methods: string[] = []
  for (const m of METHODS) {
    // Match: export async function GET( or export const GET =
    const re = new RegExp(`export\\s+(?:async\\s+)?(?:function\\s+)?${m}\\b`)
    if (re.test(source)) methods.push(m)
  }
  // Extract a summary from the first comment block.
  const comment = source.match(/\/\*\*?([\s\S]*?)\*\//)
  const summary = comment
    ? comment[1]
        .split('\n')
        .map((l) => l.replace(/^\s*\*?\s?/, '').trim())
        .filter(Boolean)
        .join(' ')
        .slice(0, 200)
    : ''
  return { methods, summary }
}

function routePathToApiPath(routePath: string): string {
  // src/app/api/users/[id]/route.ts → /users/{id}
  let p = routePath
    .replace(/^src\/app\//, '')
    .replace(/^api\//, '/')
    .replace(/\/route\.tsx?$/, '')
    .replace(/^\/api\//, '/')
  // Convert [param] to {param}
  p = p.replace(/\[([^\]]+)\]/g, '{$1}')
  if (!p.startsWith('/')) p = '/' + p
  return p
}

export async function GET(
  _req: NextRequest,
  { params }: { params: Promise<{ id: string }> },
) {
  const { id } = await params
  let user
  try {
    user = await requireSessionUser()
  } catch (err) {
    if ((err as { status?: number }).status === 401) {
      return NextResponse.json({ error: 'unauthorized' }, { status: 401 })
    }
    throw err
  }
  const { data: project } = await db
    .from('projects')
    .select('owner_id, name')
    .eq('id', id)
    .maybeSingle()
  if (!project) return NextResponse.json({ error: 'not_found' }, { status: 404 })
  if (project.owner_id !== user.id) {
    return NextResponse.json({ error: 'forbidden' }, { status: 403 })
  }

  const { data: files } = await db
    .from('project_files')
    .select('path, content')
    .eq('project_id', id)

  // Find all route files.
  const routeFiles = (files ?? []).filter(
    (f: { path: string }) =>
      (f.path.includes('/api/') || f.path.includes('pages/api/')) &&
      /\/route\.tsx?$/.test(f.path),
  )

  const paths: Record<string, Record<string, unknown>> = {}

  for (const f of routeFiles as { path: string; content: string }[]) {
    const apiPath = routePathToApiPath(f.path)
    const { methods, summary } = extractRouteInfo(f.content)
    if (methods.length === 0) continue

    paths[apiPath] = {}
    for (const method of methods) {
      paths[apiPath][method.toLowerCase()] = {
        summary: summary || `${method} ${apiPath}`,
        operationId: `${method.toLowerCase()}_${apiPath.replace(/[^a-zA-Z0-9]/g, '_')}`,
        responses: {
          '200': {
            description: 'Successful response',
            content: { 'application/json': { schema: { type: 'object' } } },
          },
          '400': { description: 'Bad request' },
          '401': { description: 'Unauthorized' },
          '404': { description: 'Not found' },
          '500': { description: 'Internal server error' },
        },
        ...(method === 'POST' || method === 'PUT'
          ? {
              requestBody: {
                content: { 'application/json': { schema: { type: 'object' } } },
              },
            }
          : {}),
      }
    }
  }

  const spec = {
    openapi: '3.1.0',
    info: {
      title: `${project.name} API`,
      version: '1.0.0',
      description: `Auto-generated OpenAPI spec for ${project.name}. Generated by Buildr.`,
    },
    servers: [
      {
        url: '/api',
        description: 'API runtime (preview)',
      },
    ],
    paths,
  }

  return NextResponse.json(spec)
}
