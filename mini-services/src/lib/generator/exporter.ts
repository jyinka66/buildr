// Export Engine (Module 5)
// ------------------------------------------------------------------
// Packages a project's virtual file system into a downloadable .zip using
// JSZip. Also exposes a GitHub push helper that uses a Personal Access
// Token to create/update files in a repository via the GitHub REST API.

import JSZip from 'jszip'
import { db } from '@/lib/db'

interface ProjectFileRow {
  id: string
  path: string
  content: string
  language: string
  generated: boolean
}

interface ProjectRow {
  id: string
  name: string
  slug: string
  description: string
  stack: string
}

export interface ExportOptions {
  /** Include node_modules-free install instructions. Default true. */
  includeReadme?: boolean
  /** Emit a fresh .env.example from current env vars. Default true. */
  includeEnvExample?: boolean
}

// ---------------------------------------------------------------------------
// Build a ZIP Blob for a project.
// ---------------------------------------------------------------------------

export async function buildProjectZip(
  projectId: string,
  _opts: ExportOptions = {},
): Promise<{ zip: Buffer; fileName: string; fileCount: number }> {
  const { data: project, error: projectError } = await db
    .from('projects')
    .select('id, name, slug, description, stack')
    .eq('id', projectId)
    .maybeSingle()

  if (projectError || !project) throw new Error('Project not found')

  const { data: fileRows, error: filesError } = await db
    .from('project_files')
    .select('id, path, content, language, generated')
    .eq('project_id', projectId)

  if (filesError) throw new Error(`Failed to load files: ${filesError.message}`)

  const files = (fileRows as ProjectFileRow[] | null) ?? []
  const projectRow = project as ProjectRow

  const zip = new JSZip()
  for (const file of files) {
    zip.file(file.path, file.content)
  }

  // Always ensure a top-level README pointing at the project name.
  if (!files.some((f) => f.path === 'README.md')) {
    zip.file(
      'README.md',
      `# ${projectRow.name}\n\n${projectRow.description}\n\nGenerated by Buildr.\n`,
    )
  }

  const buffer = await zip.generateAsync({
    type: 'nodebuffer',
    compression: 'DEFLATE',
    compressionOptions: { level: 6 },
  })

  const slug = projectRow.slug || projectRow.id
  return {
    zip: buffer,
    fileName: `${slug}.zip`,
    fileCount: files.length,
  }
}

// ---------------------------------------------------------------------------
// GitHub sync — push the project's file tree to a repository.
// Uses GitHub Contents API: create/update each file. Requires a PAT.
// ---------------------------------------------------------------------------

export interface GitHubPushInput {
  projectId: string
  token: string
  repo: string // "owner/name"
  branch: string
  commitMessage?: string
}

export interface GitHubPushResult {
  pushedFiles: number
  repo: string
  branch: string
  commitSha: string
  url: string
}

async function ghHeaders(token: string): Promise<HeadersInit> {
  return {
    Authorization: `Bearer ${token}`,
    Accept: 'application/vnd.github+json',
    'X-GitHub-Api-Version': '2022-11-28',
    'Content-Type': 'application/json',
  }
}

export async function pushToGitHub(input: GitHubPushInput): Promise<GitHubPushResult> {
  const { projectId, token, repo, branch, commitMessage } = input
  const { data: project, error: projectError } = await db
    .from('projects')
    .select('id, name, slug, description, stack')
    .eq('id', projectId)
    .maybeSingle()

  if (projectError || !project) throw new Error('Project not found')

  const { data: fileRows, error: filesError } = await db
    .from('project_files')
    .select('id, path, content, language, generated')
    .eq('project_id', projectId)

  if (filesError) throw new Error(`Failed to load files: ${filesError.message}`)

  const files = (fileRows as ProjectFileRow[] | null) ?? []

  const [owner, name] = repo.split('/')
  if (!owner || !name) throw new Error('repo must be in "owner/name" form')

  // Ensure the branch exists (try to get its sha; if 404, create from default branch).
  let branchSha: string | undefined
  const branchRes = await fetch(
    `https://api.github.com/repos/${owner}/${name}/branches/${encodeURIComponent(branch)}`,
    { headers: await ghHeaders(token) },
  )
  if (branchRes.ok) {
    const data = await branchRes.json()
    branchSha = data?.commit?.sha
  } else if (branchRes.status === 404) {
    // Create the branch off the default branch's HEAD.
    const repoRes = await fetch(`https://api.github.com/repos/${owner}/${name}`, {
      headers: await ghHeaders(token),
    })
    if (!repoRes.ok) {
      throw new Error(`Could not access repo ${repo}: ${repoRes.status}`)
    }
    const repoData = await repoRes.json()
    const defaultBranch = repoData.default_branch
    const refRes = await fetch(
      `https://api.github.com/repos/${owner}/${name}/git/refs/heads/${defaultBranch}`,
      { headers: await ghHeaders(token) },
    )
    if (!refRes.ok) {
      throw new Error(`Could not read default branch ${defaultBranch}`)
    }
    const refData = await refRes.json()
    const baseSha = refData?.object?.sha
    const createBranchRes = await fetch(
      `https://api.github.com/repos/${owner}/${name}/git/refs`,
      {
        method: 'POST',
        headers: await ghHeaders(token),
        body: JSON.stringify({
          ref: `refs/heads/${branch}`,
          sha: baseSha,
        }),
      },
    )
    if (!createBranchRes.ok) {
      throw new Error(
        `Could not create branch ${branch}: ${await createBranchRes.text()}`,
      )
    }
    const created = await createBranchRes.json()
    branchSha = created?.object?.sha
  } else {
    throw new Error(`GitHub branch lookup failed: ${branchRes.status}`)
  }

  // Push each file via the Contents API (create or update).
  let pushed = 0
  let lastSha: string | undefined = branchSha
  for (const file of files) {
    const body = {
      message: `${commitMessage ?? 'chore(buildr): sync project files'}: ${file.path}`,
      content: Buffer.from(file.content).toString('base64'),
      branch,
    }
    // Try update first (need existing file sha); fall back to create.
    const existingRes = await fetch(
      `https://api.github.com/repos/${owner}/${name}/contents/${file.path}?ref=${encodeURIComponent(branch)}`,
      { headers: await ghHeaders(token) },
    )
    const existing = existingRes.ok ? await existingRes.json() : null
    const payload = existing?.sha ? { ...body, sha: existing.sha } : body
    const upRes = await fetch(
      `https://api.github.com/repos/${owner}/${name}/contents/${file.path}`,
      {
        method: 'PUT',
        headers: await ghHeaders(token),
        body: JSON.stringify(payload),
      },
    )
    if (!upRes.ok) {
      const txt = await upRes.text()
      throw new Error(`GitHub push failed for ${file.path} (${upRes.status}): ${txt}`)
    }
    const upData = await upRes.json()
    lastSha = upData?.commit?.sha ?? lastSha
    pushed++
  }

  const url = `https://github.com/${owner}/${name}/tree/${encodeURIComponent(branch)}`
  return {
    pushedFiles: pushed,
    repo,
    branch,
    commitSha: lastSha ?? '',
    url,
  }
}

// ---------------------------------------------------------------------------
// Build a "preview bundle" — for the live preview panel we serve a single
// HTML document that inlines the project's CSS/JS so it renders in an
// iframe srcdoc. This is a best-effort renderer suitable for static HTML
// and Next.js landing pages; full SSR isn't attempted in the sandbox.
// ---------------------------------------------------------------------------

export async function buildPreviewBundle(projectId: string): Promise<{
  html: string
  isStatic: boolean
}> {
  const { data: project, error: projectError } = await db
    .from('projects')
    .select('id, name, slug, description, stack')
    .eq('id', projectId)
    .maybeSingle()

  if (projectError || !project) throw new Error('Project not found')
  const projectRow = project as ProjectRow

  const { data: fileRows, error: filesError } = await db
    .from('project_files')
    .select('id, path, content, language, generated')
    .eq('project_id', projectId)

  if (filesError) throw new Error(`Failed to load files: ${filesError.message}`)
  const files = (fileRows as ProjectFileRow[] | null) ?? []

  if (projectRow.stack === 'static-html') {
    const indexHtml = files.find((f) => f.path === 'index.html')
    const css = files.find((f) => f.path === 'styles.css')
    const js = files.find((f) => f.path === 'app.js')
    if (indexHtml) {
      let html = indexHtml.content
      if (css) {
        html = html.replace(
          '<link rel="stylesheet" href="styles.css" />',
          `<style>${css.content}</style>`,
        )
      }
      if (js) {
        html = html.replace(
          '<script src="app.js"></script>',
          `<script>${js.content}</script>`,
        )
      }
      return { html, isStatic: true }
    }
  }

  // For Next.js / Vite stacks, use the INTERACTIVE preview runtime.
  // This actually transpiles + executes the generated React code in-browser
  // via Babel Standalone + a CommonJS require() shim + React 19 createRoot.
  // The result is a LIVE, INTERACTIVE render — clicks fire, useState updates,
  // forms render. API routes are stubbed (clearly bannered).
  try {
    const { buildInteractivePreview } = await import('@/lib/generator/preview-runtime')
    const result = buildInteractivePreview(
      projectRow.name,
      projectId,
      projectRow.stack as 'nextjs' | 'react-vite',
      files.map((f) => ({ path: f.path, content: f.content, language: f.language })),
    )
    if (result && result.html) {
      return { html: result.html, isStatic: result.mode === 'static' }
    }
  } catch (err) {
    console.error('[Buildr] Interactive preview failed, falling back to structural:', err instanceof Error ? err.message : err)
  }

  // Fallback: structural preview (extracts raw JSX text)
  const page = files.find(
    (f) =>
      f.path === 'src/app/page.tsx' ||
      f.path === 'src/pages/index.tsx' ||
      f.path === 'src/App.tsx',
  )
  const css = files.find(
    (f) => f.path === 'src/app/globals.css' || f.path === 'src/index.css',
  )

  const safeCode = (page?.content ?? '')
    .replace(/export default function (\w+)/, 'function $1')
    .replace(/export default/, '')
  const stripped = safeCode
    .replace(/import [^;]+;/g, '')
    .replace(/import\s+type\s+\{[^}]+\}\s+from\s+["'][^"']+["'];?/g, '')

  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${projectRow.name} — Preview</title>
<style>
:root { color-scheme: light; }
* { box-sizing: border-box; }
body { margin: 0; font-family: system-ui, -apple-system, sans-serif; }
.buildr-preview { padding: 2rem; max-width: 1100px; margin: 0 auto; }
.buildr-banner { background: #f4f4f5; border-bottom: 1px solid #e4e4e7; padding: 0.5rem 1rem; font-size: 0.75rem; color: #52525b; }
${css?.content ?? ''}
</style>
</head>
<body>
<div class="buildr-banner">Preview — structural render of <strong>${projectRow.name}</strong>. Export &amp; run locally for the full app.</div>
<div class="buildr-preview">
<pre style="white-space:pre-wrap;font-family:ui-monospace,SFMono-Regular,monospace;font-size:0.8rem;background:#fafafa;padding:1rem;border-radius:8px;border:1px solid #eee;">${escapeHtml(stripped)}</pre>
</div>
<script>
// Preview harness — minimal React-like mount for static structural render.
// Real interactivity requires the exported project.
window.addEventListener('load', () => {
  console.log('Buildr preview loaded for ${projectRow.name}');
});
</script>
</body>
</html>`

  return { html, isStatic: false }
}

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
}
