// POST /api/projects/[id]/inject-keys — fetches secrets from the project's
// Secrets Vault and generates a runtime env loader that the generated app
// can import. This makes generated apps ACTUALLY WORK — a generated Stripe
// checkout will use the real STRIPE_SECRET_KEY from the vault.
//
// Creates:
//   1. src/lib/env.ts — reads env vars at runtime (from process.env or
//      the injected vault values)
//   2. .env.local — a .env file with the decrypted vault secrets (for local dev)
//   3. Updates the generated integration files to import from src/lib/env.ts
//      instead of process.env directly (so the vault is the single source)
//
// This closes the gap between "generated code that looks like it works" and
// "generated code that actually works with real API keys."
import { NextRequest, NextResponse } from 'next/server'
import { db } from '@/lib/db'
import { requireSessionUser } from '@/lib/session'
import { decrypt } from '@/lib/crypto'
import { audit } from '@/lib/snapshot'
import { formatFile } from '@/lib/formatter'

export async function POST(
  _req: NextRequest,
  { params }: { params: Promise<{ id: string }> },
) {
  const { id } = await params
  let user
  try {
    user = await requireSessionUser()
  } catch (err) {
    if ((err as { status?: number }).status === 401) {
      return NextResponse.json({ error: 'unauthorized' }, { status: 401 })
    }
    throw err
  }
  const { data: project } = await db
    .from('projects')
    .select('owner_id, name, stack')
    .eq('id', id)
    .maybeSingle()
  if (!project) return NextResponse.json({ error: 'not_found' }, { status: 404 })
  if (project.owner_id !== user.id) {
    return NextResponse.json({ error: 'forbidden' }, { status: 403 })
  }

  // Fetch all secrets from the vault.
  const { data: secrets, error } = await db
    .from('project_secrets')
    .select('key, value')
    .eq('project_id', id)

  if (error) {
    return NextResponse.json({ error: error.message }, { status: 500 })
  }

  if (!secrets || secrets.length === 0) {
    return NextResponse.json({
      ok: false,
      message: 'No secrets found in the vault. Add secrets (API keys) via the Secrets dialog first.',
    })
  }

  // Decrypt each secret value.
  const decryptedSecrets: Record<string, string> = {}
  const maskedSecrets: { key: string; masked: string }[] = []

  for (const secret of secrets as { key: string; value: string }[]) {
    try {
      // Try to decrypt (if encrypted). If it starts with 'plain:' or isn't
      // an encrypted payload, use as-is.
      let value = secret.value
      if (value && value.includes(':') && !value.startsWith('plain:')) {
        value = decrypt(value)
      } else if (value.startsWith('plain:')) {
        value = value.slice(6)
      }

      decryptedSecrets[secret.key] = value
      maskedSecrets.push({
        key: secret.key,
        masked: value.slice(0, 4) + '••••••' + value.slice(-4),
      })
    } catch {
      // Skip secrets that can't be decrypted.
      decryptedSecrets[secret.key] = secret.value
      maskedSecrets.push({ key: secret.key, masked: '••••••' })
    }
  }

  // 1. Generate src/lib/env.ts — a typed env loader.
  const envKeys = Object.keys(decryptedSecrets)
  const envTypes = envKeys
    .map((k) => `  ${k}: string`)
    .join('\n')

  const envAccessors = envKeys
    .map((k) => `  ${k}: process.env.${k} || '',`)
    .join('\n')

  const envLibContent = `// Environment variables — generated by Buildr.
// This module reads from process.env (populated by .env.local in development).
// Secrets are managed in the Buildr Secrets Vault and injected here.
//
// Usage in your code:
//   import { env } from '@/lib/env';
//   const stripe = new Stripe(env.STRIPE_SECRET_KEY);

interface EnvVars {
${envTypes}
}

function loadEnv(): EnvVars {
  return {
${envAccessors}
  };
}

export const env = loadEnv();

// Helper to check if a key is set.
export function hasKey(key: keyof EnvVars): boolean {
  return Boolean(env[key]);
}
`

  // 2. Generate .env.example (NOT .env.local) with placeholder values.
  // Decrypted secrets are NEVER persisted to project_files. The env.ts
  // module reads from process.env at runtime — the user must set the
  // values in their deployment environment (Vercel/Netlify/Docker env vars).
  const envExampleContent = envKeys
    .map((k) => `${k}=${'•'.repeat(8)}  # Set this in your deployment environment`)
    .join('\n') + '\n'

  // 3. Format the env.ts file with Prettier.
  const formattedEnvLib = await formatFile('src/lib/env.ts', envLibContent)

  // Save env.ts + .env.example (with masked placeholders, NOT real secrets).
  const filesToSave: { path: string; content: string; language: string }[] = [
    { path: 'src/lib/env.ts', content: formattedEnvLib, language: 'ts' },
    { path: '.env.example', content: envExampleContent, language: 'env' },
  ]

  const savedFiles: { path: string }[] = []

  for (const file of filesToSave) {
    const { data: existing } = await db
      .from('project_files')
      .select('id')
      .eq('project_id', id)
      .eq('path', file.path)
      .maybeSingle()

    if (existing) {
      await db
        .from('project_files')
        .update({ content: file.content, language: file.language, updated_at: new Date().toISOString() })
        .eq('project_id', id)
        .eq('path', file.path)
    } else {
      await db.from('project_files').insert({
        project_id: id,
        path: file.path,
        content: file.content,
        language: file.language,
        generated: true,
      })
    }
    savedFiles.push({ path: file.path })
  }

  // 4. Update integration lib files to import from src/lib/env.ts.
  //    For each integration that uses process.env, replace with env.XXX.
  const integrationPaths = [
    'src/lib/stripe.ts',
    'src/lib/supabase.ts',
    'src/lib/email.ts',
    'src/lib/twilio.ts',
    'src/lib/plaid.ts',
    'src/lib/paystack.ts',
    'src/lib/razorpay.ts',
    'src/lib/onfido.ts',
    'src/lib/auth.ts',
  ]

  let updatedIntegrations = 0
  for (const intPath of integrationPaths) {
    const { data: intFile } = await db
      .from('project_files')
      .select('content')
      .eq('project_id', id)
      .eq('path', intPath)
      .maybeSingle()

    if (!intFile?.content) continue

    let updated = intFile.content
    let changed = false

    // Replace process.env.KEY with env.KEY for each secret key.
    for (const key of envKeys) {
      const regex = new RegExp(`process\\.env\\.${key}`, 'g')
      if (regex.test(updated)) {
        updated = updated.replace(regex, `env.${key}`)
        changed = true
      }
    }

    if (changed) {
      // Add the import if not already present.
      if (!updated.includes("from '@/lib/env'") && !updated.includes('from "../lib/env"')) {
        // Add import at the top (after the last existing import).
        const importMatch = updated.match(/^import\s+[^;]+;\s*$/gm)
        if (importMatch) {
          const lastImport = importMatch[importMatch.length - 1]
          const insertPos = updated.indexOf(lastImport) + lastImport.length
          updated = updated.slice(0, insertPos) + `\nimport { env } from '@/lib/env';` + updated.slice(insertPos)
        } else {
          updated = `import { env } from '@/lib/env';\n` + updated
        }
      }

      // Format the updated file.
      const formatted = await formatFile(intPath, updated)

      await db
        .from('project_files')
        .update({ content: formatted, updated_at: new Date().toISOString() })
        .eq('project_id', id)
        .eq('path', intPath)

      updatedIntegrations++
    }
  }

  const secretCount = Object.keys(decryptedSecrets).length

  await audit(
    'keys.inject',
    { secretsInjected: secretCount, integrationsUpdated: updatedIntegrations },
    user.id,
    id,
  )

  return NextResponse.json({
    ok: true,
    secretsInjected: secretCount,
    integrationsUpdated: updatedIntegrations,
    filesSaved: savedFiles,
    maskedSecrets,
    message: `Injected ${secretCount} secret(s) into the generated app. ${updatedIntegrations} integration file(s) updated to use src/lib/env.ts. Set the secret values in your deployment environment (Vercel/Netlify env vars or .env.local).`,
  })
}
