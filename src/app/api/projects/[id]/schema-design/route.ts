// POST /api/projects/[id]/schema-design — generates a Prisma schema from a
// visual model definition (tables + fields + relations) and saves it to the
// project. Optionally generates SQL migration too.
//
// The visual model is a JSON array of tables, each with:
//   { name, fields: [{ name, type, optional, unique, default, isId }] }
//   relations: [{ from, to, type: '1:1' | '1:n' | 'n:m' }]
//
// We convert this to a valid prisma/schema.prisma file and save it.
import { NextRequest, NextResponse } from 'next/server'
import { db } from '@/lib/db'
import { requireSessionUser } from '@/lib/session'
import { guessLanguage } from '@/lib/llm/code-generator'
import { audit } from '@/lib/snapshot'

interface ModelField {
  name: string
  type: string // 'String' | 'Int' | 'Boolean' | 'DateTime' | 'Json' | 'Float' | 'text'
  optional?: boolean
  unique?: boolean
  default?: string
  isId?: boolean
}

interface ModelTable {
  name: string
  fields: ModelField[]
}

interface ModelRelation {
  from: string // table name
  to: string // table name
  type: '1:1' | '1:n' | 'n:m'
}

interface DesignBody {
  tables: ModelTable[]
  relations: ModelRelation[]
  generateSql?: boolean
}

const PRISMA_TYPES: Record<string, string> = {
  string: 'String',
  text: 'String',
  int: 'Int',
  integer: 'Int',
  float: 'Float',
  boolean: 'Boolean',
  datetime: 'DateTime',
  json: 'Json',
  bytes: 'Bytes',
  decimal: 'Decimal',
  bigint: 'BigInt',
}

function generatePrismaSchema(tables: ModelTable[], relations: ModelRelation[]): string {
  const lines: string[] = [
    '// Prisma schema generated by Buildr Schema Designer',
    '',
    'generator client {',
    '  provider = "prisma-client-js"',
    '}',
    '',
    'datasource db {',
    '  provider = "postgresql"',
    '  url      = env("DATABASE_URL")',
    '}',
    '',
  ]

  // Generate models.
  for (const table of tables) {
    lines.push(`model ${table.name} {`)
    for (const field of table.fields) {
      const type = PRISMA_TYPES[field.type.toLowerCase()] || field.type
      const optional = field.optional ? '?' : ''
      const parts = [`  ${field.name}`, `${type}${optional}`]

      const attrs: string[] = []
      if (field.isId) attrs.push('@id')
 if (field.isId && type === 'String') attrs.push('@default(cuid())')
      if (field.isId && type === 'Int') attrs.push('@default(autoincrement())')
      if (field.unique) attrs.push('@unique')
      if (field.default) {
        if (type === 'String') attrs.push(`@default("${field.default}")`)
        else if (type === 'DateTime') attrs.push(`@default(now())`)
        else if (type === 'Boolean') attrs.push(`@default(${field.default})`)
        else attrs.push(`@default(${field.default})`)
      }

      if (attrs.length) parts.push(attrs.join(' '))
      lines.push(parts.join('  '))
    }

    // Add relation fields.
    for (const rel of relations.filter(r => r.from === table.name || r.to === table.name)) {
      if (rel.type === '1:n') {
        // The "1" side gets a relation field + @relation
        const other = rel.to === table.name ? rel.from : rel.to
        lines.push(`  ${other.toLowerCase()} ${other}? @relation(fields: [${other.toLowerCase()}Id], references: [id])`)
        lines.push(`  ${other.toLowerCase()}Id String?`)
      } else if (rel.type === 'n:m') {
        const other = rel.to === table.name ? rel.from : rel.to
        lines.push(`  ${other.toLowerCase()}s ${other}[]`)
      } else if (rel.type === '1:1') {
        const other = rel.to === table.name ? rel.from : rel.to
        lines.push(`  ${other.toLowerCase()} ${other}? @relation(fields: [${other.toLowerCase()}Id], references: [id])`)
        lines.push(`  ${other.toLowerCase()}Id String? @unique`)
      }
    }

    lines.push('}')
    lines.push('')
  }

  return lines.join('\n')
}

function generateSqlMigration(tables: ModelTable[], relations: ModelRelation[]): string {
  const lines: string[] = [
    '-- Migration generated by Buildr Schema Designer',
    '',
  ]

  for (const table of tables) {
    const columnDefs: string[] = []
    for (const field of table.fields) {
      const sqlType = field.type.toLowerCase() === 'string' || field.type.toLowerCase() === 'text'
        ? 'TEXT'
        : field.type.toLowerCase() === 'int' || field.type.toLowerCase() === 'integer'
          ? 'INTEGER'
          : field.type.toLowerCase() === 'float'
            ? 'REAL'
            : field.type.toLowerCase() === 'boolean'
              ? 'BOOLEAN'
              : field.type.toLowerCase() === 'datetime'
                ? 'TIMESTAMPTZ'
                : field.type.toLowerCase() === 'json'
                  ? 'JSONB'
                  : 'TEXT'
      const nullable = field.optional ? '' : ' NOT NULL'
      const unique = field.unique ? ' UNIQUE' : ''
      const pk = field.isId ? ' PRIMARY KEY' : ''
      const def = field.default
        ? field.type.toLowerCase() === 'string'
          ? ` DEFAULT '${field.default}'`
          : field.type.toLowerCase() === 'datetime'
            ? ` DEFAULT now()`
            : ` DEFAULT ${field.default}`
        : ''
      columnDefs.push(`  "${field.name}" ${sqlType}${pk}${nullable}${unique}${def}`)
    }

    lines.push(`CREATE TABLE IF NOT EXISTS "${table.name}" (`)
    lines.push(columnDefs.join(',\n'))
    lines.push(');')
    lines.push('')
  }

  // Add foreign keys for relations.
  for (const rel of relations) {
    if (rel.type === '1:n' || rel.type === '1:1') {
      lines.push(`ALTER TABLE "${rel.from}" ADD COLUMN IF NOT EXISTS "${rel.to.toLowerCase()}Id" TEXT;`)
      lines.push(`ALTER TABLE "${rel.from}" ADD CONSTRAINT fk_${rel.from}_${rel.to} FOREIGN KEY ("${rel.to.toLowerCase()}Id") REFERENCES "${rel.to}"("id");`)
      lines.push('')
    } else if (rel.type === 'n:m') {
      const joinTable = `${rel.from}_${rel.to}`
      lines.push(`CREATE TABLE IF NOT EXISTS "${joinTable}" (`)
      lines.push(`  "${rel.from.toLowerCase()}Id" TEXT NOT NULL,`)
      lines.push(`  "${rel.to.toLowerCase()}Id" TEXT NOT NULL,`)
      lines.push(`  PRIMARY KEY ("${rel.from.toLowerCase()}Id", "${rel.to.toLowerCase()}Id")`)
      lines.push(');')
      lines.push('')
    }
  }

  return lines.join('\n')
}

export async function POST(
  req: NextRequest,
  { params }: { params: Promise<{ id: string }> },
) {
  const { id } = await params
  let user
  try {
    user = await requireSessionUser()
  } catch (err) {
    if ((err as { status?: number }).status === 401) {
      return NextResponse.json({ error: 'unauthorized' }, { status: 401 })
    }
    throw err
  }
  const { data: project } = await db
    .from('projects')
    .select('owner_id')
    .eq('id', id)
    .maybeSingle()
  if (!project) return NextResponse.json({ error: 'not_found' }, { status: 404 })
  if (project.owner_id !== user.id) {
    return NextResponse.json({ error: 'forbidden' }, { status: 403 })
  }

  const body = (await req.json()) as DesignBody
  if (!body.tables || !Array.isArray(body.tables) || body.tables.length === 0) {
    return NextResponse.json({ error: 'tables array is required.' }, { status: 400 })
  }

  const prismaSchema = generatePrismaSchema(body.tables, body.relations || [])
  const filesSaved: { path: string }[] = []

  // Save the Prisma schema.
  const { data: existingPrisma } = await db
    .from('project_files')
    .select('id')
    .eq('project_id', id)
    .eq('path', 'prisma/schema.prisma')
    .maybeSingle()

  if (existingPrisma) {
    await db.from('project_files')
      .update({ content: prismaSchema, updated_at: new Date().toISOString() })
      .eq('project_id', id)
      .eq('path', 'prisma/schema.prisma')
  } else {
    await db.from('project_files').insert({
      project_id: id,
      path: 'prisma/schema.prisma',
      content: prismaSchema,
      language: 'prisma',
      generated: true,
    })
  }
  filesSaved.push({ path: 'prisma/schema.prisma' })

  // Optionally generate SQL migration.
  if (body.generateSql) {
    const sqlMigration = generateSqlMigration(body.tables, body.relations || [])
    const migrationPath = `supabase/migrations/${Date.now()}_schema_design.sql`
    await db.from('project_files').insert({
      project_id: id,
      path: migrationPath,
      content: sqlMigration,
      language: 'sql',
      generated: true,
    })
    filesSaved.push({ path: migrationPath })
  }

  await audit('schema.design', { tables: body.tables.length, relations: body.relations?.length || 0 }, user.id, id)

  return NextResponse.json({
    ok: true,
    prismaSchema,
    sqlMigration: body.generateSql ? generateSqlMigration(body.tables, body.relations || []) : undefined,
    filesSaved,
  })
}
